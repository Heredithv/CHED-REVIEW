export function lookupDriveLinkTitle(url: string): string | null {
  if (!url) return null;
  const trimmed = url.trim().replace(/\.$/, "");
  const idMatch = trimmed.match(/(?:\/d\/|\/folders\/|[?&]id=)([a-zA-Z0-9_-]{15,})/);
  if (idMatch && DRIVE_ID_TITLES[idMatch[1]]) {
    return DRIVE_ID_TITLES[idMatch[1]];
  }
  if (DRIVE_ID_TITLES[trimmed]) {
    return DRIVE_ID_TITLES[trimmed];
  }
  return null;
}
